// Issued alerts linked to this event or to none, covering a selected
// district, with at least one status change inside the range.
function alertsFor(ctx) {
  return ALERTS.filter(
    (alert) =>
      (alert.event === ctx.event.id || alert.event === null) &&
      alert.districtIds.some((id) => ctx.districtIds.includes(id)) &&
      (ctx.hazardType === null || alert.hazardType === ctx.hazardType) &&
      alert.history.some((change) => ctx.inRange(change.at)),
  );
}

function compileAlertTimeline(ctx) {
  const entries = alertsFor(ctx)
    .flatMap((alert) =>
      alert.history
        .filter((change) => ctx.inRange(change.at))
        .map((change) => ({
          at: change.at,
          date: dayOf(change.at),
          alert: { id: alert.id, referenceNo: alert.referenceNo },
          status: change.status,
          version: change.version,
          hazardType: alert.hazardType,
          severity: alert.severity,
          areas: alert.areas,
        })),
    )
    .sort(
      (a, b) =>
        a.at.localeCompare(b.at) ||
        a.alert.referenceNo.localeCompare(b.alert.referenceNo) ||
        a.version - b.version,
    );

  const perDay = new Map();
  entries.forEach((entry) => perDay.set(entry.date, (perDay.get(entry.date) ?? 0) + 1));
  const alerts = new Set(entries.map((entry) => entry.alert.id)).size;
  return {
    result: {
      alerts,
      entries,
      days: ctx.days.map((date) => ({ date, entries: perDay.get(date) ?? null })),
    },
    recordDays: new Set(perDay.keys()),
    summary: { alertsIssued: alerts },
  };
}

// Of n recipients, the seeder never reaches 1 in 17 on any channel; of the
// rest, about 1 in 9 push and 1 in 23 SMS sends fail, and 1 in 11 audible
// alerts is sent without being confirmed delivered.
const neverReached = (n) => Math.ceil(n / 17);

function channelOutcomes(n) {
  const never = neverReached(n);
  const rest = n - never;
  const missed = { PUSH: Math.round(rest / 9), SMS: Math.round(rest / 23), AUDIBLE: 0 };
  const unconfirmed = { PUSH: 0, SMS: 0, AUDIBLE: Math.round(rest / 11) };
  return CHANNELS.map((channel) => ({
    channel,
    attempted: n,
    delivered: rest - missed[channel] - unconfirmed[channel],
    failed: never + missed[channel],
  }));
}

const withRate = (row) => ({
  ...row,
  deliveryRate: row.attempted === 0 ? null : row.delivered / row.attempted,
});

function compileCitizensReached(ctx) {
  const firstAt = (alert) => alert.history.find((change) => ctx.inRange(change.at)).at;
  const alerts = alertsFor(ctx).sort(
    (a, b) => firstAt(a).localeCompare(firstAt(b)) || a.referenceNo.localeCompare(b.referenceNo),
  );

  // Every send in the range: one delivery record per recipient and channel.
  const sends = alerts.flatMap((alert) =>
    alert.history
      .filter((change) => ctx.inRange(change.at))
      .map((change) => ({
        alert,
        date: dayOf(change.at),
        outcomes: channelOutcomes(citizensIn(alert.districtIds)),
      })),
  );
  const sum = (rows) =>
    CHANNELS.map((channel) => {
      const ofChannel = rows.filter((row) => row.channel === channel);
      return {
        channel,
        attempted: ofChannel.reduce((total, row) => total + row.attempted, 0),
        delivered: ofChannel.reduce((total, row) => total + row.delivered, 0),
        failed: ofChannel.reduce((total, row) => total + row.failed, 0),
      };
    });

  const perDay = new Map();
  sends.forEach(({ date, outcomes }) => {
    const counts = perDay.get(date) ?? { attempted: 0, delivered: 0 };
    outcomes.forEach((row) => {
      counts.attempted += row.attempted;
      counts.delivered += row.delivered;
    });
    perDay.set(date, counts);
  });

  // Each citizen counts once, however many alerts and channels reached them.
  const targeted = citizensIn([...new Set(sends.flatMap(({ alert }) => alert.districtIds))]);
  const reached = targeted - neverReached(targeted);
  const reachedRate = targeted === 0 ? null : reached / targeted;
  return {
    result: {
      citizensReached: reached,
      citizensTargeted: targeted,
      reachedRate,
      perChannel: sum(sends.flatMap(({ outcomes }) => outcomes)).map(withRate),
      perAlert: alerts.map((alert) => {
        const recipients = citizensIn(alert.districtIds);
        return {
          alert: { id: alert.id, referenceNo: alert.referenceNo },
          citizensReached: recipients - neverReached(recipients),
          perChannel: sum(
            sends.filter((send) => send.alert === alert).flatMap(({ outcomes }) => outcomes),
          ).map(({ channel, attempted, delivered }) => ({ channel, attempted, delivered })),
        };
      }),
      days: ctx.days.map((date) => ({
        date,
        attempted: perDay.get(date)?.attempted ?? null,
        delivered: perDay.get(date)?.delivered ?? null,
      })),
    },
    recordDays: new Set(perDay.keys()),
    summary: { citizensReached: reached, citizensTargeted: targeted, reachedRate },
  };
}

// A district's occupancy at each moment is the sum of its shelters' latest
// occupants (a record from before the range gives the starting value); a
// day's peak is the highest of those sums that day.
function compileOccupancy(ctx) {
  const selected = OCCUPANCY_RECORDS.filter((record) => ctx.districtIds.includes(record.district));
  const latest = new Map(ctx.districtIds.map((id) => [id, new Map()]));
  const peaks = new Map(ctx.districtIds.map((id) => [id, new Map()]));

  selected
    .filter((record) => dayOf(record.recordedAt) < ctx.from)
    .sort((a, b) => a.recordedAt.localeCompare(b.recordedAt))
    .forEach((record) => latest.get(record.district).set(record.shelter, record.occupants));

  const moments = new Map();
  selected
    .filter((record) => ctx.inRange(record.recordedAt))
    .forEach((record) =>
      moments.set(record.recordedAt, [...(moments.get(record.recordedAt) ?? []), record]),
    );
  [...moments.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .forEach(([moment, records]) => {
      records.forEach((record) =>
        latest.get(record.district).set(record.shelter, record.occupants),
      );
      const day = dayOf(moment);
      new Set(records.map((record) => record.district)).forEach((district) => {
        const total = [...latest.get(district).values()].reduce((sum, value) => sum + value, 0);
        peaks.get(district).set(day, Math.max(peaks.get(district).get(day) ?? 0, total));
      });
    });

  const recordDays = new Set();
  const districts = ctx.districts.map((district) => {
    const dayPeaks = peaks.get(district.id);
    dayPeaks.forEach((_peak, day) => recordDays.add(day));
    let peak = null;
    ctx.days.forEach((date) => {
      if (dayPeaks.has(date) && (peak === null || dayPeaks.get(date) > peak.value)) {
        peak = { value: dayPeaks.get(date), date };
      }
    });
    return {
      district,
      days: ctx.days.map((date) => ({ date, peak: dayPeaks.get(date) ?? null })),
      peak,
    };
  });

  // The highest daily total across the districts; a tie goes to the earlier day.
  let summary = { peakOccupancy: null, peakOccupancyDate: null };
  ctx.days.forEach((date) => {
    const onDay = districts.map((row) => row.days.find((day) => day.date === date).peak);
    if (onDay.every((value) => value === null)) return;
    const total = onDay.reduce((sum, value) => sum + (value ?? 0), 0);
    if (summary.peakOccupancy === null || total > summary.peakOccupancy) {
      summary = { peakOccupancy: total, peakOccupancyDate: date };
    }
  });
  return { result: { districts }, recordDays, summary };
}

// Quantities by district x supply type x organisation, summed across units.
function compileDistribution(ctx) {
  const records = DISTRIBUTIONS.filter(
    (record) =>
      ctx.districtIds.includes(record.district) &&
      (ctx.organisationId === null || record.organisation.id === ctx.organisationId) &&
      ctx.inRange(record.distributedAt),
  );
  const rows = new Map();
  const perDay = new Map();
  records.forEach((record) => {
    const key = [record.district, record.supplyType, record.organisation.id].join('|');
    const row = rows.get(key) ?? {
      district: ctx.districts.find(({ id }) => id === record.district),
      supplyType: record.supplyType,
      organisation: record.organisation,
      quantity: 0,
    };
    row.quantity += record.quantity;
    rows.set(key, row);
    const day = dayOf(record.distributedAt);
    perDay.set(day, (perDay.get(day) ?? 0) + record.quantity);
  });

  const sorted = [...rows.values()].sort(
    (a, b) =>
      a.district.name.localeCompare(b.district.name) ||
      SUPPLY_TYPES.indexOf(a.supplyType) - SUPPLY_TYPES.indexOf(b.supplyType) ||
      a.organisation.name.localeCompare(b.organisation.name),
  );
  const total = sorted.reduce((sum, row) => sum + row.quantity, 0);
  return {
    result: {
      rows: sorted,
      total,
      days: ctx.days.map((date) => ({ date, quantity: perDay.get(date) ?? null })),
    },
    recordDays: new Set(perDay.keys()),
    summary: { itemsDistributed: total },
  };
}

// The A1 filters each section honours (§14.9), as on the server.
const SECTION_FILTERS = {
  alertTimeline: ['districtId', 'hazardType'],
  citizensReached: ['districtId', 'hazardType'],
  occupancyOverTime: ['districtId'],
  resourceDistribution: ['districtId', 'organisationId'],
};
const NO_FILTERS = { hazardType: null, districtId: null, organisationId: null };
const HAZARD_TYPES = ['FLOOD', 'LANDSLIDE', 'CYCLONE', 'DROUGHT'];

const COMPILERS = {
  alertTimeline: compileAlertTimeline,
  citizensReached: compileCitizensReached,
  occupancyOverTime: compileOccupancy,
  resourceDistribution: compileDistribution,
};

// Step 10: the days without records, consecutive days merged into one gap.
function gapsIn(section, days, recordDays) {
  const gaps = [];
  days.forEach((date, index) => {
    if (recordDays.has(date)) return;
    const last = gaps[gaps.length - 1];
    if (last && last.to === days[index - 1]) {
      last.to = date;
    } else {
      gaps.push({ section, from: date, to: date, reason: GAP_REASONS[section] });
    }
  });
  return gaps;
}

// The report object as the server returns it (§14.2). A district filter
// compiles every section for that one district; the hazard and organisation
// filters reach only the sections that honour them (A1, §14.9).
function buildReport(event, { from, to, districtIds, sections }, filters = NO_FILTERS) {
  const districts = event.districts.filter(({ id }) => districtIds.includes(id));
  const compiledFor = filters.districtId
    ? districts.filter(({ id }) => id === filters.districtId)
    : districts;
  const base = {
    event,
    from,
    to,
    districts: compiledFor,
    districtIds: compiledFor.map(({ id }) => id),
    days: daysBetween(from, to),
    inRange: (instant) => {
      const day = dayOf(instant);
      return day >= from && day <= to;
    },
  };
  const contextFor = (key) => ({
    ...base,
    hazardType: SECTION_FILTERS[key].includes('hazardType') ? filters.hazardType : null,
    organisationId: SECTION_FILTERS[key].includes('organisationId') ? filters.organisationId : null,
  });

  const summary = {
    alertsIssued: null,
    citizensReached: null,
    citizensTargeted: null,
    reachedRate: null,
    peakOccupancy: null,
    peakOccupancyDate: null,
    itemsDistributed: null,
  };
  const compiled = SECTION_KEYS.filter((key) => sections.includes(key)).map((key) => {
    const section = COMPILERS[key](contextFor(key));
    Object.assign(summary, section.summary);
    return { key, ...section };
  });

  // E2: no report when every requested section is empty.
  if (compiled.every(({ recordDays }) => recordDays.size === 0)) {
    throw apiError(404, 'NO_DATA_FOR_SELECTION', 'No data is available for this selection.');
  }

  const gaps = compiled.flatMap(({ key, recordDays }) => gapsIn(key, base.days, recordDays));
  const generatedAt = new Date().toISOString();
  return {
    id: `66fc4a1b2c3d4e5f6a7b${(0x9e00 + nextReport++).toString(16)}`,
    event: {
      id: event.id,
      name: event.name,
      hazardType: event.hazardType,
      startDate: event.startDate,
      endDate: event.endDate,
    },
    generatedBy: OFFICER,
    generatedAt,
    dateFrom: from,
    dateTo: to,
    districts,
    filters: { ...filters },
    summary,
    hasGaps: gaps.length > 0,
    gaps,
    sections: compiled.map(({ key, result }) => ({ key, result })),
    createdAt: generatedAt,
  };
}

const copy = (value) => JSON.parse(JSON.stringify(value));

// --- The API ---

async function listClosedEvents() {
  await delay();
  takeFailure();
  return EVENTS.filter((event) => event.status === 'CLOSED')
    .sort((a, b) => b.startDate.localeCompare(a.startDate))
    .map(copy);
}

async function generate(params = {}) {
  await delay();
  takeFailure();
  const errors = shapeErrors(params);
  if (errors.length > 0) throw validationError(errors);

  const event = EVENTS.find(({ id }) => id === params.eventId);
  if (!event) throw apiError(404, 'NOT_FOUND', 'Hazard event not found.');
  takeFailure({ generating: true });
  if (event.status !== 'CLOSED') {
    throw apiError(
      409,
      'EVENT_NOT_CLOSED',
      `A report can only be generated for a CLOSED event – current status: ${event.status}`,
    );
  }
  const problems = parameterErrors(event, params);
  if (problems.length > 0) throw validationError(problems);

  const report = buildReport(event, params);
  reports.set(report.id, report);
  return copy(report);
}

async function getReport(id) {
  await delay();
  takeFailure();
  const report = reports.get(id);
  if (!report) throw apiError(404, 'NOT_FOUND', 'Post-event report not found.');
  return copy(report);
}

async function listRecent(eventId) {
  await delay();
  takeFailure();
  if (!isId(eventId)) {
    throw validationError([
      {
        field: 'eventId',
        message: eventId === undefined ? 'eventId is required' : 'must be a valid id',
      },
    ]);
  }
  return [...reports.values()]
    .filter((report) => report.event.id === eventId)
    .sort((a, b) => b.generatedAt.localeCompare(a.generatedAt) || b.id.localeCompare(a.id))
    .slice(0, RECENT_LIMIT)
    .map((report) => copy(listItem(report)));
}

// The refine body's shape and the report-specific rules, in the server's
// order (§14.9): a bad shape first, then no filter set, then a district the
// report doesn't cover.
function filterErrors(report, filters) {
  const errors = [];
  const { hazardType = null, districtId = null, organisationId = null } = filters;
  if (hazardType !== null && !HAZARD_TYPES.includes(hazardType)) {
    errors.push({ field: 'hazardType', message: `must be one of [${HAZARD_TYPES.join(', ')}]` });
  }
  if (districtId !== null && !isId(districtId)) {
    errors.push({ field: 'districtId', message: 'must be a valid id' });
  }
  if (organisationId !== null && !isId(organisationId)) {
    errors.push({ field: 'organisationId', message: 'must be a valid id' });
  }
  if (errors.length > 0) return errors;
  if (hazardType === null && districtId === null && organisationId === null) {
    return [{ field: 'filters', message: 'must set at least one filter' }];
  }
  if (districtId !== null && !report.districts.some(({ id }) => id === districtId)) {
    return [{ field: 'districtId', message: "must be one of the report's districts" }];
  }
  return [];
}

async function refine(id, filters = {}) {
  await delay();
  takeFailure();
  const source = reports.get(id);
  if (!source) throw apiError(404, 'NOT_FOUND', 'Post-event report not found.');
  const errors = filterErrors(source, filters);
  if (errors.length > 0) throw validationError(errors);
  const wanted = { ...NO_FILTERS, ...filters };
  if (
    wanted.organisationId !== null &&
    !ALL_ORGANISATIONS.some(({ id: orgId }) => orgId === wanted.organisationId)
  ) {
    throw apiError(404, 'NOT_FOUND', 'Organisation not found.');
  }

  const event = EVENTS.find(({ id: eventId }) => eventId === source.event.id);
  const report = buildReport(
    event,
    {
      from: source.dateFrom,
      to: source.dateTo,
      districtIds: source.districts.map(({ id: districtId }) => districtId),
      sections: source.sections.map(({ key }) => key),
    },
    wanted,
  );
  reports.set(report.id, report);
  return copy(report);
}

async function listOrganisations() {
  await delay();
  takeFailure();
  return ALL_ORGANISATIONS.map(copy);
}

// A report without its summary, gaps and sections (§14.5).
function listItem(report) {
  return {
    id: report.id,
    event: { id: report.event.id, name: report.event.name },
    generatedBy: report.generatedBy,
    generatedAt: report.generatedAt,
    dateFrom: report.dateFrom,
    dateTo: report.dateTo,
    districts: report.districts,
    filters: report.filters,
    hasGaps: report.hasGaps,
  };
}

