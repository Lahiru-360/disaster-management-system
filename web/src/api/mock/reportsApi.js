function apiError(status, code, message, errors) {
  const error = new Error(message);
  error.response = {
    status,
    data: {
      success: false,
      error: errors ? { code, message, errors } : { code, message },
    },
  };
  return error;
}

const validationError = (errors) =>
  apiError(400, 'VALIDATION_ERROR', 'Request validation failed.', errors);

// What axios rejects with when the request never got a response.
function networkError() {
  const error = new Error('Network Error');
  error.code = 'ERR_NETWORK';
  return error;
}

// Fakes the next call's failure, then goes back to normal. A faked 409 is
// kept for the next generate, the only call that can meet it.
function takeFailure({ generating = false } = {}) {
  const failure = pendingFailure;
  if (failure === 'notClosed' && !generating) return;
  pendingFailure = null;
  if (failure === 'network') throw networkError();
  if (failure === 'server') {
    throw apiError(500, 'INTERNAL_ERROR', 'Something went wrong. Please try again.');
  }
  if (failure === 'notClosed') {
    throw apiError(
      409,
      'EVENT_NOT_CLOSED',
      'A report can only be generated for a CLOSED event – current status: ACTIVE',
    );
  }
}

// --- Days (§14.1) ---

const dayOf = (instant) => new Date(Date.parse(instant) + OFFSET_MS).toISOString().slice(0, 10);

function isDay(value) {
  if (typeof value !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const time = Date.parse(`${value}T00:00:00.000Z`);
  return !Number.isNaN(time) && new Date(time).toISOString().slice(0, 10) === value;
}

function daysBetween(from, to) {
  const days = [];
  for (let time = Date.parse(from); time <= Date.parse(to); time += DAY_MS) {
    days.push(new Date(time).toISOString().slice(0, 10));
  }
  return days;
}

const isId = (value) => typeof value === 'string' && /^[0-9a-f]{24}$/i.test(value);

// --- Validation (E1, §14.3), in the server's order ---

// The request's shape, as the server's Joi schema words it.
function shapeErrors({ eventId, from, to, districtIds, sections }) {
  const errors = [];
  if (eventId === undefined) errors.push({ field: 'eventId', message: 'eventId is required' });
  else if (!isId(eventId)) errors.push({ field: 'eventId', message: 'must be a valid id' });

  [
    ['from', from],
    ['to', to],
  ].forEach(([field, value]) => {
    if (value === undefined) errors.push({ field, message: `${field} is required` });
    else if (!isDay(value)) errors.push({ field, message: 'must be a date as YYYY-MM-DD' });
  });

  const listErrors = (field, list, { what, isValid, invalidMessage }) => {
    if (list === undefined) return errors.push({ field, message: `${field} is required` });
    if (!Array.isArray(list)) return errors.push({ field, message: `${field} must be an array` });
    if (list.length === 0)
      return errors.push({ field, message: `must select at least one ${what}` });
    return list.forEach((item, index) => {
      if (!isValid(item)) {
        errors.push({ field: `${field}.${index}`, message: invalidMessage(index) });
      } else if (list.indexOf(item) !== index) {
        errors.push({
          field: `${field}.${index}`,
          message: `${field}[${index}] contains a duplicate value`,
        });
      }
    });
  };
  listErrors('districtIds', districtIds, {
    what: 'district',
    isValid: isId,
    invalidMessage: () => 'must be a valid id',
  });
  listErrors('sections', sections, {
    what: 'section',
    isValid: (key) => SECTION_KEYS.includes(key),
    invalidMessage: (index) => `sections[${index}] must be one of [${SECTION_KEYS.join(', ')}]`,
  });
  return errors;
}

// The range and districts against the closed event (DMS-159).
function parameterErrors(event, { from, to, districtIds }) {
  const start = dayOf(event.startDate);
  const end = dayOf(event.endDate);
  const errors = [];
  if (from > to) {
    errors.push({ field: 'from', message: 'must not be after to' });
  } else if (from < start) {
    errors.push({ field: 'from', message: `must be on or after the event start date ${start}` });
  }
  if (to > end) {
    errors.push({ field: 'to', message: `must be on or before the event end date ${end}` });
  }
  const affected = new Set(event.districts.map(({ id }) => id));
  if (districtIds.some((id) => !affected.has(id))) {
    errors.push({ field: 'districtIds', message: 'must be a district the event affected' });
  }
  return errors;
}

